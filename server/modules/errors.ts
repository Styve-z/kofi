export type BusinessErrorCode = keyof typeof BUSINESS_ERRORS;

export class BusinessError extends Error {
  constructor(public readonly code: BusinessErrorCode) {
    super(code);
    this.name = "BusinessError";
  }
}

/** Convertit une erreur métier en erreur tRPC typée ; laisse remonter le reste sans détail interne. */
export function toTrpcError(error: unknown): TRPCError {
  if (error instanceof TRPCError) return error;
  if (error instanceof BusinessError) return new TRPCError({ code: BUSINESS_ERRORS[error.code], message: error.code });
  console.error("[KOFI] Erreur inattendue", error);
  return new TRPCError({ code: "INTERNAL_SERVER_ERROR", message: "UNEXPECTED_ERROR" });
}
